# --------------------------------------------------------------------------
# Seeding logic
# --------------------------------------------------------------------------


async def _already_seeded(session: AsyncSession) -> bool:
    """Idempotency check: the admin user's existence is the seed marker."""
    result = await session.execute(select(User.id).where(User.email == _ADMIN_EMAIL))
    return result.scalar_one_or_none() is not None


async def _knowledge_articles_already_seeded(session: AsyncSession) -> bool:
    """A separate idempotency check, deliberately independent of
    `_already_seeded`: `knowledge_articles` was added after this script's
    other fixtures, so a deployment that already ran `seed()` (and would
    otherwise skip everything via the admin-user check) still gets these
    backfilled the next time the script runs."""
    result = await session.execute(select(KnowledgeArticle.id).limit(1))
    return result.scalar_one_or_none() is not None


async def _seed_users(session: AsyncSession) -> dict[str, User]:
    """Create the default users; return them keyed by email for lookup."""
    logger.info("Creating users...")
    users: dict[str, User] = {}
    for spec in _USERS:
        user = User(
            email=spec["email"],
            password_hash=hash_password(spec["password"]),
            full_name=spec["full_name"],
            role=spec["role"],
            is_active=True,
        )
        session.add(user)
        users[spec["email"]] = user
    await session.flush()  # assign PKs so tickets can reference them below
    return users


async def _seed_customers(session: AsyncSession) -> list[Customer]:
    """Create the demo customers, in `_CUSTOMERS` order."""
    logger.info("Creating customers...")
    customers = [
        Customer(
            name=spec["name"],
            email=spec["email"],
            company=spec["company"],
            tier=spec["tier"],
        )
        for spec in _CUSTOMERS
    ]
    session.add_all(customers)
    await session.flush()
    return customers


async def _seed_tickets(
    session: AsyncSession,
    customers: list[Customer],
    users: dict[str, User],
) -> None:
    """Create the demo tickets, wired to `customers`/`users` via relationships."""
    logger.info("Creating tickets...")
    tickets = [
        Ticket(
            customer=customers[spec["customer_index"]],
            assigned_agent=users[spec["assigned_to"]] if spec["assigned_to"] else None,
            subject=spec["subject"],
            description=spec["description"],
            priority=spec["priority"],
            status=spec["status"],
            ai_summary=spec["ai_summary"],
        )
        for spec in _TICKETS
    ]
    session.add_all(tickets)
    await session.flush()


async def _seed_knowledge_articles(session: AsyncSession) -> None:
    """Create the demo knowledge-base articles `KnowledgeBaseSearchTool` retrieves."""
    logger.info("Creating knowledge articles...")
    articles = [
        KnowledgeArticle(
            category=spec["category"],
            title=spec["title"],
            content=spec["content"],
        )
        for spec in _KNOWLEDGE_ARTICLES
    ]
    session.add_all(articles)
    await session.flush()


async def seed() -> None:
    """Seed the database with baseline development data, idempotently.

    Runs as a single transaction: either every row commits, or (on any
    exception) nothing does.
    """
    settings = get_settings()
    if settings.environment == "production" and not os.environ.get("ALLOW_SEED_IN_PRODUCTION"):
        logger.error(
            "Refusing to run the dev seed script against a production "
            "database (ENVIRONMENT=production). Set "
            "ALLOW_SEED_IN_PRODUCTION=1 to override."
        )
        sys.exit(1)

    async with async_session_factory() as session:
        try:
            already_seeded = await _already_seeded(session)
            if already_seeded:
                logger.info("Database already seeded (users/customers/tickets). Skipping those.")
            else:
                users = await _seed_users(session)
                customers = await _seed_customers(session)
                await _seed_tickets(session, customers, users)

            if await _knowledge_articles_already_seeded(session):
                logger.info("Knowledge articles already seeded. Skipping.")
            else:
                await _seed_knowledge_articles(session)

            await session.commit()
            logger.info("Database seeded successfully.")
        except Exception:
            logger.error("Seeding failed; rolling back transaction.", exc_info=True)
            await session.rollback()
            raise


def main() -> None:
    """Entry point for `python -m backend.scripts.seed`."""
    configure_logging()
    asyncio.run(seed())


if __name__ == "__main__":
    main()

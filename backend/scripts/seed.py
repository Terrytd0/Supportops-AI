"""Seed the database with baseline development data.

Usage:
    python -m backend.scripts.seed

Reuses the project's existing components rather than reimplementing them:
- `backend.database.session.async_session_factory` for the DB connection
- `backend.database.models.*` (ORM models) and `backend.database.enums.*`
- `backend.auth.hashing.hash_password` for password hashing

Idempotent: if the admin user (`_ADMIN_EMAIL`) already exists, the script
prints a message and exits without touching the database further. Combined
with `users.email` being UNIQUE at the schema level, this also means a race
between two concurrent runs fails safely (the second run's insert violates
the unique constraint and the whole transaction rolls back) rather than
producing duplicate rows.

`agent_runs`, `approval_requests`, and `audit_logs` are intentionally left
empty — they're operational data generated by using the application, not
fixtures. `knowledge_articles` is seeded, unlike those three: it's reference
content (`backend.tools.knowledge_base.KnowledgeBaseSearchTool` reads it to
ground CrewAI specialist responses), not something usage generates, so an
empty table would just mean every agent response is ungrounded rather than
demonstrating the real retrieval path.
"""

